"""Build preparation files only. Requires Python openpyxl; never connects to a DB."""
from pathlib import Path
import csv
import re
from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.comments import Comment
from openpyxl.worksheet.datavalidation import DataValidation

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'templates' / 'setup'
OUT.mkdir(parents=True, exist_ok=True)
wb = Workbook()
wb.remove(wb.active)

def sheet(name, headers, rows=(), rules=None):
    ws = wb.create_sheet(name)
    ws.append(headers)
    for row in rows:
        ws.append(row)
    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = f'A1:{ws.cell(1, len(headers)).column_letter}{max(2, ws.max_row)}'
    ws.sheet_view.showGridLines = False
    for cell in ws[1]:
        cell.fill = PatternFill('solid', fgColor='DCEBFF')
        cell.font = Font(bold=True, color='18375F')
        cell.alignment = Alignment(wrap_text=True, vertical='center')
        if rules and cell.value in rules:
            cell.comment = Comment(rules[cell.value], 'Studio Management')
    ws.row_dimensions[1].height = 30
    for col in ws.columns:
        field = col[0].value
        ws.column_dimensions[col[0].column_letter].width = min(65, max(22, len(field) + 4))
    return ws

instructions = [
    ('Purpose', 'Preparation templates only. No application screens or database records are changed.'),
    ('Database', 'Target database: postgres. Schema: studio. No credentials belong in these files.'),
    ('Import support', 'There is no built-in Excel upload. These are not directly importable database dumps; a reviewed mapping/import step is required.'),
    ('Order', 'Review Master Entities and value sheets first, then Packages and Staff. Studio Profile is a separate settings record.'),
    ('Defaults', 'Master rows are defaults from source migrations, not an export of your live database. Preserve existing custom values and check duplicates.'),
    ('New values', 'Add rows beneath the headers. Do not add IDs: the database generates them. Codes are generated by the application.'),
    ('Mapping', 'Master Entities uses entity_name; value sheets use value_name. An importer must resolve each sheet to its existing entity by code and pass name/description/display_order/is_active through normal master validation.'),
    ('Compatibility', 'Do not overwrite stored values, aliases or existing codes. Event Type imports must also maintain legacy event-type links through the existing master creation service.'),
    ('Payment methods', 'Payment Type is the legacy master name for payment methods. Advance/Partial/Final are payment purposes, not entries for this sheet.'),
    ('Blank sheets', 'Packages, Staff and Studio Profile contain no sample records. Fill only your real details.'),
    ('Required fields', 'See Field Rules and header comments. Do not rename headers.'),
    ('Mobile numbers', 'Exactly 10 digits when supplied; no spaces or country prefix. Excel mobile/phone cells are formatted as text.'),
    ('Dates', 'Use valid YYYY-MM-DD dates. Staff DOB cannot be in the future. DOB cells are text to keep CSV dates stable.'),
    ('Amounts', 'Use numbers without currency symbols or thousands separators; at most 2 decimal places.'),
    ('CSV files', 'UTF-8 CSV files are supplied for each data sheet. When opening CSV in Excel, set mobile and date columns to Text; CSV cannot preserve Excel formatting.'),
    ('Validation', 'Excel checks assist entry but do not replace application validation. Do not directly import these sheets into production tables.'),
    ('Staff vs users', 'Staff records support booking assignments. They do not create login accounts. No user-password template is included.'),
]
sheet('Instructions', ['topic', 'instructions'], instructions)
rules = [
    ('Master Entities', 'entity_name', 'Required', 'Unique master name; 1-150 characters. Existing names identify existing entities.'),
    ('Master values', 'value_name', 'Required', '1-150 characters; no duplicate generated codes within an entity. Codes normalize case and punctuation.'),
    ('Master sheets', 'description', 'Optional', 'Up to 2000 characters.'),
    ('Master sheets', 'display_order', 'Required', 'Whole number 0-2147483647; lower values appear first.'),
    ('Master sheets', 'is_active', 'Required', 'TRUE or FALSE.'),
    ('Packages', 'name', 'Required', '1-500 characters.'),
    ('Packages', 'package_type', 'Optional', 'Must match an active stored Package Type value; defaults shown on Package Type sheet.'),
    ('Packages', 'amount', 'Required', '0 to 9999999999.99; at most 2 decimal places.'),
    ('Packages', 'description', 'Optional', 'Up to 2000 characters.'),
    ('Staff', 'name', 'Required', '1-500 characters.'),
    ('Staff', 'mobile', 'Optional', 'Exactly 10 digits when supplied. Keep as text.'),
    ('Staff', 'dob', 'Required', 'Valid YYYY-MM-DD date, not in the future.'),
    ('Staff', 'email', 'Required', 'Valid email address; the application normalizes it to lowercase.'),
    ('Staff', 'address', 'Required', '1-2000 characters.'),
    ('Studio Profile', 'name', 'Required', '1-500 characters. One profile row only.'),
    ('Studio Profile', 'phone', 'Optional', 'Exactly 10 digits when supplied. Keep as text.'),
    ('Studio Profile', 'email', 'Optional', 'Valid email address when supplied.'),
    ('Studio Profile', 'address', 'Optional', 'Up to 2000 characters.'),
    ('Studio Profile', 'tagline', 'Optional', 'Up to 120 characters.'),
    ('Studio Profile', 'signatory_name', 'Optional', 'Up to 100 characters.'),
    ('Studio Profile', 'signatory_title', 'Optional', 'Up to 100 characters.'),
    ('Studio Profile', 'receipt_footer', 'Optional', 'Up to 300 characters.'),
]
sheet('Field Rules', ['sheet', 'field', 'requirement', 'rule'], rules)

sql = (ROOT / 'backend/database/migrations/004_master_management.up.sql').read_text(encoding='utf-8')
sql += (ROOT / 'backend/database/migrations/006_customer_title_gender.up.sql').read_text(encoding='utf-8')
values = {}
for code, content in re.findall(r"WHEN '([A-Z_]+)' THEN ARRAY\[(.*?)\]", sql):
    values[code] = [v.replace("''", "'") for v in re.findall(r"'((?:[^']|'')*)'", content)]
entities = [('ALBUM_TYPE', 'Album Type'), ('PAYMENT_TYPE', 'Payment Type'),
            ('EVENT_TYPE', 'Event Type'), ('EXPENSE_CATEGORY', 'Expense Category'),
            ('EQUIPMENT_CATEGORY', 'Equipment Category'), ('ALBUM_SIZE', 'Album Size'),
            ('PACKAGE_TYPE', 'Package Type'), ('CUSTOMER_TITLE', 'Customer Title'),
            ('CUSTOMER_GENDER', 'Customer Gender')]
sheet('Master Entities', ['entity_name', 'description', 'display_order', 'is_active'],
      [(name, '', i, True) for i, (_, name) in enumerate(entities, 1)])
for code, name in entities:
    assert values[code], code
    sheet(name, ['value_name', 'description', 'display_order', 'is_active'],
          [(v, '', i, True) for i, v in enumerate(values[code], 1)])
for name, headers in [
    ('Packages', ['name', 'package_type', 'amount', 'description']),
    ('Staff', ['name', 'mobile', 'dob', 'email', 'address']),
    ('Studio Profile', ['name', 'phone', 'email', 'address', 'tagline', 'signatory_name', 'signatory_title', 'receipt_footer']),
]:
    sheet(name, headers, rules={r[1]: f'{r[2]}. {r[3]}' for r in rules if r[0] == name})

for ws in wb:
    for cell in ws[1]:
        column = cell.column_letter
        if cell.value in ('mobile', 'phone', 'dob'):
            for n in range(2, 1002):
                ws[f'{column}{n}'].number_format = '@'
        if cell.value == 'is_active':
            dv = DataValidation(type='list', formula1='"TRUE,FALSE"')
        elif cell.value == 'display_order':
            dv = DataValidation(type='whole', operator='between', formula1=0, formula2=2147483647)
        elif ws.title == 'Packages' and cell.value == 'amount':
            dv = DataValidation(type='custom', formula1=f'AND(ISNUMBER({column}2),{column}2>=0,{column}2<=9999999999.99,ROUND({column}2,2)={column}2)')
        elif cell.value in ('mobile', 'phone'):
            dv = DataValidation(type='custom', formula1=f'AND(ISTEXT({column}2),LEN({column}2)=10,SUMPRODUCT(--ISNUMBER(FIND(MID({column}2,ROW($1:$10),1),"0123456789")))=10)', allow_blank=True)
        else:
            continue
        dv.errorTitle = 'Check the field rules'
        dv.error = 'Enter a value in the required format.'
        dv.showErrorMessage = True
        ws.add_data_validation(dv)
        dv.add(f'{column}2:{column}1001')

for ws in wb:
    if ws.title in ('Instructions', 'Field Rules'):
        ws.column_dimensions['B'].width = 38 if ws.title == 'Field Rules' else 110
        if ws.title == 'Field Rules':
            ws.column_dimensions['D'].width = 100
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = Alignment(wrap_text=True, vertical='top')
            ws.row_dimensions[row[0].row].height = 45
        continue
    path = OUT / (ws.title.lower().replace(' ', '_') + '.csv')
    # Do not export blank formatted rows from the empty templates.
    with path.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        for row in ws.iter_rows(values_only=True):
            if any(v is not None for v in row):
                writer.writerow(['TRUE' if v is True else 'FALSE' if v is False else '' if v is None else v for v in row])

path = OUT / 'studio_setup_templates.xlsx'
wb.save(path)
check = load_workbook(path)
assert len(check.sheetnames) == 15
assert check['Staff']['B2'].number_format == '@'
assert check['Staff']['A2'].value is None
assert check['Packages']['A2'].value is None
assert check['Customer Title']['A2'].value == 'Mr.'
assert len(list(OUT.glob('*.csv'))) == 13
print(f'Created and checked {path}: 15 sheets, 13 CSV templates; no database changes.')
